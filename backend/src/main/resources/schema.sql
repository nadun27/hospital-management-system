CREATE TABLE IF NOT EXISTS departments (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(100) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS roles (
 code VARCHAR(30) PRIMARY KEY, name VARCHAR(80) NOT NULL
);
